/** 常用 VK 码显示名（主/渲染进程共用） */
const VK_NAMES: Record<number, string> = {
  0x08: 'Backspace', 0x09: 'Tab', 0x0d: 'Enter', 0x14: 'CapsLock', 0x1b: 'Esc',
  0x20: 'Space', 0x21: 'PageUp', 0x22: 'PageDown', 0x23: 'End', 0x24: 'Home',
  0x25: '←', 0x26: '↑', 0x27: '→', 0x28: '↓', 0x2c: 'PrtSc', 0x2d: 'Insert', 0x2e: 'Delete',
  0x5b: 'LWin', 0x5c: 'RWin',
  0xa0: 'LShift', 0xa1: 'RShift', 0xa2: 'LCtrl', 0xa3: 'RCtrl', 0xa4: 'LAlt', 0xa5: 'RAlt',
  0x30: '0', 0x31: '1', 0x32: '2', 0x33: '3', 0x34: '4', 0x35: '5', 0x36: '6', 0x37: '7',
  0x38: '8', 0x39: '9',
  0xba: ';', 0xbb: '=', 0xbc: ',', 0xbd: '-', 0xbe: '.', 0xbf: '/', 0xc0: '`',
  0xdb: '[', 0xdc: '\\', 0xdd: ']', 0xde: "'",
  0x60: 'Num0', 0x61: 'Num1', 0x62: 'Num2', 0x63: 'Num3', 0x64: 'Num4', 0x65: 'Num5',
  0x66: 'Num6', 0x67: 'Num7', 0x68: 'Num8', 0x69: 'Num9',
  0x6a: 'Num*', 0x6b: 'Num+', 0x6d: 'Num-', 0x6e: 'Num.', 0x6f: 'Num/'
}

export function vkName(vk: number): string {
  if (VK_NAMES[vk]) return VK_NAMES[vk]
  if (vk >= 0x41 && vk <= 0x5a) return String.fromCharCode(vk) // A-Z
  if (vk >= 0x70 && vk <= 0x7b) return `F${vk - 0x70 + 1}` // F1-F12
  return `VK_${vk.toString(16).toUpperCase()}`
}
