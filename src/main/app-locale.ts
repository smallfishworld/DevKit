export type MainMessageKey = keyof (typeof mainMessages)['zh-CN']

let currentLocale: AppLocale = DEFAULT_APP_LOCALE

export function getAppLocale(): AppLocale {
  return currentLocale
}

export function setAppLocale(value: unknown): AppLocale {
  currentLocale = sanitizeAppLocale(value)
  return currentLocale
}

export async function initializeAppLocale(): Promise<AppLocale> {
  try {
    const { getSection } = await import('./services/macro/configStore')
    const saved = await getSection<LocaleSettings>('locale', DEFAULT_LOCALE_SETTINGS)
    currentLocale = sanitizeLocaleSettings(saved).language
  } catch {
    currentLocale = DEFAULT_APP_LOCALE
  }
  return currentLocale
}

export function mainText(key: MainMessageKey, params: Record<string, string | number> = {}): string {
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    (mainMessages[currentLocale][key] ?? mainMessages[DEFAULT_APP_LOCALE][key]) as string
  )
}
