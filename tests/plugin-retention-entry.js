const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { createHash } = require('node:crypto')
const { PluginSources, parseSourceIndex } = require('../src/main/services/plugins/sources')
const { cleanSerialArchives, LogRetentionStore } = require('../src/main/services/terminal/log-retention')
const { OFFICIAL_PLUGIN_SOURCE } = require('../src/shared/plugins')
const { retentionCutoff, validLogRetention } = require('../src/shared/log-retention')

async function test() {
  const root = await fs.mkdtemp(join(tmpdir(), 'devkit-plugin-retention-'))
  try {
    const indexUrl = 'https://example.test/index.json'
    const bytes = Buffer.from(JSON.stringify({ manifest: { id: 'devkit.test', version: '1.0.0' }, files: {} }))
    const sha256 = createHash('sha256').update(bytes).digest('hex')
    const entry = { id: 'devkit.test', name: 'Test plug-in', version: '1.0.0', url: 'plugin.json', sha256 }
    let download = bytes
    const index = Buffer.from(JSON.stringify({ version: 1, plugins: [entry] }))
    const sourceService = new PluginSources(root, async (address) => address === indexUrl ? index : download)
    const [official] = await sourceService.list()
    assert.equal(official.url, OFFICIAL_PLUGIN_SOURCE.url)
    assert.equal(official.enabled, true)
    assert.equal(official.official, true)
    await assert.rejects(sourceService.update(official.id), /可停用/)
    await sourceService.update(official.id, false)
    assert.equal((await new PluginSources(root).list())[0].enabled, false)
    await assert.rejects(sourceService.add('Duplicate official', official.url), /已添加/)
    await sourceService.update(official.id, true)
    const [, source] = await sourceService.add('Fixture', indexUrl)
    await assert.rejects(sourceService.add('Duplicate', indexUrl), /已添加/)
    await assert.rejects(sourceService.add('Insecure', 'http://example.test/index.json'), /HTTPS/)
    assert.throws(() => parseSourceIndex({ version: 1, plugins: [entry, entry] }, indexUrl), /重复/)
    const [, refreshed] = await sourceService.refresh(source.id)
    assert.equal(refreshed.entries[0].url, 'https://example.test/plugin.json')
    assert.deepEqual(await sourceService.package(source.id, entry.id, sha256, 4096), bytes)
    download = Buffer.from('changed')
    await assert.rejects(sourceService.package(source.id, entry.id, sha256, 4096), /SHA-256/)
    await sourceService.update(source.id, false)
    await assert.rejects(sourceService.refresh(source.id), /先启用/)
    await assert.rejects(sourceService.package(source.id, entry.id, sha256, 4096), /变化/)
    assert.deepEqual((await sourceService.update(source.id)).map((row) => row.id), [official.id])
    const configPath = join(root, 'plugin-sources.json')
    await fs.writeFile(configPath, JSON.stringify([{ id: 'legacy-official', name: '旧来源', enabled: false, url: official.url, entries: [] }]))
    const migrated = await sourceService.list()
    assert.equal(migrated.length, 1)
    assert.equal(migrated[0].id, official.id)
    assert.equal(migrated[0].enabled, false)
    console.log('  PASS 扩展源持久化、索引验证、启停移除和下载校验')

    const store = new LogRetentionStore(root)
    assert.deepEqual(await store.read(), { enabled: true, months: 12 })
    assert.equal(validLogRetention({ enabled: true, months: 1.5 }), false)
    await Promise.all([store.save({ enabled: true, months: 6 }), store.save({ enabled: false, months: 24 })])
    assert.deepEqual(await new LogRetentionStore(root).read(), { enabled: false, months: 24 })
    assert.equal(new Date(retentionCutoff(new Date('2024-03-31T12:00:00Z'), 1)).toISOString(), '2024-02-29T12:00:00.000Z')
    const archive = async (name, time) => {
      const path = join(root, name)
      await fs.writeFile(path, 'capture')
      await fs.utimes(path, time, time)
      return path
    }
    const old = new Date('2024-01-01T00:00:00Z')
    const expired = await archive('COM1-20240101-000000-abcdef12.log', old)
    const open = await archive('COM2-20240101-000000-abcdef12.log', old)
    const recent = await archive('COM3-20240101-000000-abcdef12.log', new Date('2025-11-01T00:00:00Z'))
    const exported = await archive('serial-20240101-000000.log', old)
    await fs.link(exported, join(root, 'COM4-20240101-000000-abcdef12.log'))
    const report = await cleanSerialArchives([root, root], 12, () => new Set([open]), new Date('2025-11-18T00:00:00Z'))
    assert.deepEqual(report, { removed: 1, failed: 0 })
    await assert.rejects(fs.access(expired), { code: 'ENOENT' })
    await Promise.all([open, recent, exported].map((p) => fs.access(p)))
    console.log('  PASS 默认 12 个月、UTC 月末、过期文件及活动/导出文件保护')
  } finally { await fs.rm(root, { recursive: true, force: true }) }
}

test().catch((error) => { console.error(error); process.exitCode = 1 })
